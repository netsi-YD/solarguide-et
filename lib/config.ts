/**
 * Centralized editable assumptions for SolarGuide Ethiopia (solarguide-et).
 *
 * NOTE: Every price and financial/technical parameter below is an ASSUMPTION
 * representing typical Ethiopian solar market & utility estimates. Actual quotes
 * vary by brand, supplier, region, exchange rate, and installation complexity.
 */

export interface AssumptionMeta {
  key: keyof SolarConfig;
  label: string;
  value: number;
  unit: string;
  isAssumption: true;
  note: string;
}

export interface SolarConfig {
  /** ASSUMPTION: Solar PV panel + inverter/controller cost per kW in Ethiopian Birr (ETB) */
  panelCostPerKwEtb: number;
  /** ASSUMPTION: Battery storage cost per kWh in Ethiopian Birr (ETB) */
  batteryCostPerKwhEtb: number;
  /** ASSUMPTION: Installation, wiring, mounting & balance-of-system overhead percentage (0.15 = 15%) */
  installationOverheadPct: number;
  /** ASSUMPTION: Cost range variance around the midpoint estimate (0.15 = ±15% for low/high range) */
  costRangeVariancePct: number;
  /** ASSUMPTION: Grid electricity tariff per kWh in Ethiopian Birr (ETB) */
  gridTariffPerKwhEtb: number;
  /** ASSUMPTION: Backup generator effective fuel & maintenance cost per kWh in Ethiopian Birr (ETB) */
  generatorFuelCostPerKwhEtb: number;
  /** ASSUMPTION: Total system losses (20% = 0.20) covering inverter, wiring, dust, and temperature */
  systemLosses: number;
  /** ASSUMPTION: Battery maximum depth of discharge (80% = 0.80) */
  batteryDepthOfDischarge: number;
  /** ASSUMPTION: Days of battery autonomy without solar charging (1 day) */
  batteryAutonomyDays: number;
  /** ASSUMPTION: Standard days per month used for monthly savings projections (30 days) */
  daysPerMonth: number;
  /** ASSUMPTION: Default daily power cut / outage duration in hours (0 = backup mode off) */
  defaultOutageHoursPerDay: number;
  /** ASSUMPTION: Maximum supported outage duration per day in hours for backup sizing (12 hours) */
  maxOutageHoursPerDay: number;
}

